const MONTH_NAMES = {30:1,60:2,90:3,120:4,150:5,180:6,210:7,240:8,270:9,300:10,330:11};

/* 生成 365 天地图：{day, stage, title, theme, kind} */
function buildDayMap(){
  const map = [];
  for(let d=1; d<=30; d++){
    const kind = d===30 ? "monthly-test" : (d%7===0 ? "weekly-test" : "lesson");
    map.push({ day:d, stage:1, title:STAGE1_TITLES[d-1], theme:"发音入门", kind });
  }
  for(const sid of [2,3,4,5,6]){
    const cfg = STAGE_WEEKS[sid];
    let d = cfg.start;
    const stageEnd = STAGES[sid-1].range[1];
    for(const wk of cfg.weeks){
      for(const t of wk.days){
        pushGenerated(map, d, sid, wk.theme, t, stageEnd); d++;
      }
      if(d <= stageEnd){
        const label = MONTH_NAMES[d] ? `月度测试 ${MONTH_NAMES[d]}` : `${wk.theme} · 周测试`;
        const kind = MONTH_NAMES[d] ? "monthly-test" : "weekly-test";
        map.push({ day:d, stage:sid, title:label, theme:wk.theme, kind });
        d++;
      }
    }
    for(const t of cfg.tail){
      if(d > stageEnd) break;
      pushGenerated(map, d, sid, "综合复习", t, stageEnd); d++;
    }
    while(d <= stageEnd){
      pushGenerated(map, d, sid, "综合复习", "阶段综合复习", stageEnd); d++;
    }
  }
  const last = map.find(m=>m.day===365);
  if(last){ last.title = "Day 365 毕业总测试"; last.kind = "final-test"; }
  else map.push({ day:365, stage:6, title:"Day 365 毕业总测试", theme:"总测试", kind:"final-test" });
  return map;
}

function pushGenerated(map, d, sid, theme, title, stageEnd){
  let kind = "outline";
  if(d === 365) kind = "final-test";
  else if(d === stageEnd) kind = "stage-test";
  else if(MONTH_NAMES[d]){ kind = "monthly-test"; title = `月度测试 ${MONTH_NAMES[d]} · ${title}`; }
  map.push({ day:d, stage:sid, title, theme, kind });
}

const DAY_MAP = buildDayMap();

